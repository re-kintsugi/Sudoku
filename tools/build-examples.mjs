// Mines generated puzzles for a clear, real example of each technique the
// solver knows and writes js/examples.js for the strategy guide's diagrams.
// Run: node tools/build-examples.mjs [puzzles]
import fs from 'fs';
import { generateOnce, PEERS } from '../js/sudoku.js';
import { basicCandidates, _internals } from '../js/solver.js';

const { TECHNIQUES, apply, findStep } = _internals;
const N = +process.argv[2] || 1500;
const bit = (d) => 1 << d;
const sees = (a, b) => a !== b && PEERS[a].includes(b);

// Techniques drawn around one digit: show that digit's candidates everywhere.
const DIGIT_TECHS = new Set(['pointing', 'claiming', 'x-wing', 'swordfish', 'jellyfish', 'finned-x-wing', 'sashimi-x-wing',
  'finned-swordfish', 'sashimi-swordfish', 'finned-jellyfish', 'sashimi-jellyfish', 'x-chain']);
// Techniques whose cells are a house to shade rather than a pattern.
const HOUSE_TECHS = new Set(['full-house', 'hidden-single']);

function toSpec(st, s) {
  const spec = { tech: s.tech, values: st.values.join(''), cands: {}, pattern: [], focus: s.focus || [], elims: s.elims, place: s.place, shade: [], lines: [], text: s.text };
  if (HOUSE_TECHS.has(s.tech)) { spec.shade = s.cells; spec.digit = s.place.digit; }
  else spec.pattern = s.cells;
  if (DIGIT_TECHS.has(s.tech)) {
    const d = s.elims[0][1];
    spec.digit = d;
    for (let c = 0; c < 81; c++) if (!st.values[c] && (st.cands[c] & bit(d))) spec.cands[c] = bit(d);
    if (s.tech === 'pointing' || s.tech === 'claiming') spec.shade = [];
  } else if (!HOUSE_TECHS.has(s.tech)) {
    for (const c of [...s.cells, ...s.elims.map((e) => e[0])]) if (!st.values[c]) spec.cands[c] = st.cands[c];
    if (s.place) spec.cands[s.place.cell] = st.cands[s.place.cell];
  }
  const cells = s.cells;
  if (s.tech === 'xy-wing' || s.tech === 'xyz-wing') spec.lines = [[cells[0], cells[1], 'w'], [cells[0], cells[2], 'w']];
  if (s.tech === 'xy-chain' || s.tech === 'remote-pair') {
    for (let k = 0; k + 1 < cells.length; k++) spec.lines.push([cells[k], cells[k + 1], 'w']);
  }
  if (s.tech === 'x-chain') {
    for (let k = 0; k + 1 < cells.length; k++) spec.lines.push([cells[k], cells[k + 1], k % 2 === 0 ? 's' : 'w']);
  }
  if (s.tech === 'w-wing') {
    const [c1, c2, p, q] = cells;
    const [a, b] = sees(c1, p) && sees(c2, q) ? [p, q] : [q, p];
    spec.lines = [[c1, a, 'w'], [a, b, 's'], [b, c2, 'w']];
  }
  return spec;
}

// Smaller patterns with fewer eliminations make clearer pictures.
const score = (s) => s.cells.length + s.elims.length * 2 + (s.text.length / 80);

const best = {};
const t0 = Date.now();
for (let k = 0; k < N; k++) {
  const { puzzle } = generateOnce(0);
  const st = { values: puzzle.slice(), cands: basicCandidates(puzzle) };
  for (let guard = 0; guard < 300 && st.values.some((v) => !v); guard++) {
    // Try every technique here (the last, forcing chains, only when needed).
    for (const fn of TECHNIQUES.slice(0, -1)) {
      const s = fn(st);
      if (!s) continue;
      if (!best[s.tech] || score(s) < best[s.tech].score) best[s.tech] = { score: score(s), spec: toSpec(st, s) };
    }
    const s = findStep(st);
    if (!s) break;
    if (s.tech === 'forcing-chain' && (!best[s.tech] || score(s) < best[s.tech].score)) best[s.tech] = { score: score(s), spec: toSpec(st, s) };
    apply(st, s);
  }
  if (k % 100 === 99) console.error(`${k + 1} puzzles, ${Object.keys(best).length} techniques, ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}
const out = Object.fromEntries(Object.entries(best).map(([k, v]) => [k, v.spec]));
fs.writeFileSync(new URL('../js/examples.js', import.meta.url),
  `// Generated by tools/build-examples.mjs: real positions illustrating each technique.\nexport const EXAMPLES = ${JSON.stringify(out)};\n`);
console.error('found:', Object.keys(out).sort().join(', '));
